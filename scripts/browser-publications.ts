/**
 * The publication library as one browser-ready module.
 *
 * The editor's preview has to read a pasted BibTeX entry the way the site
 * does, and the site's reader is TypeScript in `src/lib`. Rather than keep a
 * second copy that can drift, this strips the types from those files and joins
 * them into a single module with no imports, which `/admin` can load directly.
 * Node removes only the type syntax and leaves the rest as written, so what the
 * browser runs is what the tests exercised.
 */
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

/** In dependency order: each may import only from those before it. */
const SOURCES = ['../src/lib/bibtex.ts', '../src/lib/publications.ts'];

export function buildPublicationModule(): string {
  const parts = SOURCES.map((path) => {
    const source = readFileSync(new URL(path, import.meta.url), 'utf8');
    return stripTypeScriptTypes(source, { mode: 'strip' })
      // Their imports are each other, and are now in the same file.
      .replace(/^import [^;]*;\s*$/gm, '');
  });
  return `// GENERATED by scripts/browser-publications.ts from src/lib. Do not edit.\n${parts.join('\n')}`;
}
